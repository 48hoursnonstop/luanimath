test('timeline, builders, updaters and replacement',function()
    local calls=0;local value=l.ValueTracker(0)
    local dot=l.Dot():add_updater(function(m) calls=calls+1;m:move_to(l.vec(value:get_value(),0,0)) end)
    local s=l.Scene(function() end,{frame_rate=10})
    s:add(dot,value)
    s:play(value:animate{rate_func=l.linear}:set_value(2),{run_time=1})
    equal(s.frame_count,10);equal(s.time,1);equal(dot:get_center(),2*l.RIGHT)
    assert(calls>=10)
    local target=l.Square();s:play(l.ReplacementTransform(dot,target),{run_time=0})
    assert(s.mobjects[#s.mobjects]==target)
    s:play(l.FadeOut(target),{run_time=0.2});equal(#s.mobjects,1)
    equal(s.frame_count,12);s:wait(0.25);equal(s.frame_count,15)
    dot:clear_updaters();equal(#dot.updaters,0)
end)
test('succession captures each starting state at its actual start',function()
    local m=l.Square()
