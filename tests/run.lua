local l=require('luanim')
local U=require('luanim.util')
local tests,checks=0,0
local function equal(a,b,tolerance)
    checks=checks+1
    if type(a)=='table' and type(b)=='table' then
        assert(#a==#b,'table lengths differ: '..#a..' vs '..#b)
        for i=1,#a do equal(a[i],b[i],tolerance) end
    elseif type(a)=='number' and type(b)=='number' then
        assert(math.abs(a-b)<=(tolerance or 1e-10),('%.17g != %.17g'):format(a,b))
    else assert(a==b,tostring(a)..' != '..tostring(b)) end
end
local function fails(fn) checks=checks+1;assert(not pcall(fn),'expected rejection') end
local function test(name,fn)
    local ok,err=xpcall(fn,debug.traceback)
    assert(ok,name..': '..tostring(err));tests=tests+1
end

test('vectors and Rodrigues rotation',function()
    equal(l.RIGHT+l.UP,{1,1,0});equal(2*l.LEFT,{-2,0,0})
    equal(l.vec.rotate(l.RIGHT,math.pi/2,l.OUT),l.UP)
    equal(l.vec.rotate(l.UP,math.pi/2,l.RIGHT),l.OUT)
    equal(l.vec.cross(l.RIGHT,l.UP),l.OUT)
    fails(function() return l.vec.normalize(l.ORIGIN) end)
    fails(function() return l.RIGHT/0 end)
    fails(function() return l.vec(0/0,0,0) end)
end)
test('cubic subdivision and corner paths',function()
    local c={l.vec(0,0),l.vec(1,2),l.vec(2,-1),l.vec(3,1)}
    local left,right=l.bezier.split(c,0.3)
    equal(left[4],right[1]);equal(left[4],l.bezier.point(c,0.3))
    local part=l.bezier.partial(c,0.2,0.8)
    equal(part[1],l.bezier.point(c,0.2));equal(part[4],l.bezier.point(c,0.8))
    fails(function() l.bezier.partial(c,0.8,0.2) end)
    fails(function() l.VMobject():set_points({{0,0,0}}) end)
    local empty=l.VMobject();equal(empty:get_num_curves(),0)
    fails(function() empty:point_from_proportion(0) end)
end)
