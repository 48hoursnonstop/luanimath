    fails(function() a:add(group) end)
    fails(function() group:add(l.ValueTracker()) end)
    local copy=group:copy();copy:shift(l.RIGHT)
    equal(group:get_center(),l.ORIGIN);equal(copy:get_center(),l.RIGHT)
    local shared=l.Group(l.Group(a),l.Group(a))
