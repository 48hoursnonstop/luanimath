test('transformations and layout',function()
    local m=l.Square():shift(2*l.RIGHT):scale(0.5)
    equal(m:get_center(),2*l.RIGHT);equal(m:get_width(),1)
    m:rotate(math.pi/2,{about_point=l.ORIGIN});equal(m:get_center(),2*l.UP)
    m:apply_matrix({{1,0},{0,2}});equal(m:get_center(),4*l.UP)
    local a,b=l.Square(),l.Square()
    b:next_to(a,l.RIGHT,{buff=0.5});equal(b:get_center(),2.5*l.RIGHT)
    local group=l.VGroup(a,b):arrange(l.UP,{buff=0.25});equal(group:get_center(),l.ORIGIN)
    equal(b:get_bottom()[2]-a:get_top()[2],0.25)
    fails(function() m:apply_matrix({{1},{2}}) end)
    fails(function() m:stretch(2,0) end)
end)
