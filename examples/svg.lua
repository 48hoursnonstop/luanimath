local l=require('luanimath')
return l.Scene(function(s)
    local title=l.Text('SVG · curvas, estilos y referencias',{font='Liberation Sans',font_size=42}):shift(2.8*l.UP)
    local shape=l.SVGMobject('tests/svg_assets/use.svg',{height=2.6,fill_color=l.BLUE})
    s:add(title);s:play(l.Write(shape),{run_time=1})
    s:play(l.Rotate(shape,l.PI/4),{run_time=1})
    local target=l.SVGMobject('tests/svg_assets/arcs.svg',{height=2.5,stroke_color=l.YELLOW,stroke_width=6})
    s:play(l.Transform(shape,target),{run_time=1.5})
    s:wait(.5)
end)
