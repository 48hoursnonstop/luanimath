local l=require('luanimath')
return l.Scene(function(s)
    local title=l.Text('Tipografía · estilos dentro del texto',{font='Liberation Sans',font_size=42}):shift(2.8*l.UP)
    local rich=l.MarkupText('<b>luanimath</b> <span foreground="#58c4dd"><i>Lua nativo</i></span>',{font='Liberation Sans',font_size=58}):shift(.7*l.UP)
    local gradient=l.Text('matemáticas en Lua',{font='Noto Sans',font_size=52,gradient={l.BLUE,l.GREEN},t2w={Lua='BOLD'}}):shift(.7*l.DOWN)
    s:add(title);s:play(l.Write(rich),{run_time=1});s:play(l.Write(gradient),{run_time=1})
    s:play(rich:animate():rotate(.12),gradient:animate():shift(.3*l.DOWN),{run_time=1})
    s:play(l.Unwrite(rich),l.Unwrite(gradient),{run_time=1});s:wait(.5)
end)
