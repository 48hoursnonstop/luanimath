local l=require('luanimath')
return l.Scene(function(s)
    local square=l.Square{side_length=1.8,color=l.BLUE,fill_opacity=0.25}:shift(2*l.LEFT)
    local circle=l.Circle{radius=0.9,color=l.GREEN,fill_opacity=0.25}:shift(2*l.RIGHT)
    s:play(l.Create(square),l.Create(circle),{run_time=1})
    s:play(l.Rotate(square,math.pi/2),circle:animate():shift(4*l.LEFT),{run_time=1.5})
    local target=l.Triangle{color=l.YELLOW,fill_opacity=0.4}:move_to(square:get_center())
    s:play(l.Transform(square,target),{run_time=1})
    s:play(l.FadeOut(circle),{run_time=0.5})
    s:wait(0.5)
end)
