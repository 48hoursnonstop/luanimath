local l=require('luanimath')
return l.Scene(function(s)
    local title=l.Text('Glifos · cada letra es geometría',{font='Liberation Sans',font_size=42}):shift(2.8*l.UP)
    local text=l.Text('luanimath',{font='Noto Sans',font_size=110})
    s:add(title);s:play(l.Write(text),{run_time=1})
    s:play(text:slice(1,3):animate():set_color(l.BLUE):shift(.4*l.UP),{run_time=1})
    s:play(text:animate():set_font_size(140):rotate(-.1),{run_time=1})
    s:play(l.Unwrite(text),{run_time=1});s:wait(.5)
end)
